static void csiphy_hw_version_read(struct csiphy_device *csiphy,
				   struct device *dev)
{
	struct csiphy_device_regs *regs = csiphy->regs;
	u32 hw_version;

	writel(CSIPHY_3PH_CMN_CSI_COMMON_CTRL6_SHOW_REV_ID, csiphy->base +
	       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 6));

	hw_version = readl_relaxed(csiphy->base +
		CSIPHY_3PH_CMN_CSI_COMMON_STATUSn(regs->offset,
						  regs->common_status_offset, 12));
	hw_version |= readl_relaxed(csiphy->base +
		CSIPHY_3PH_CMN_CSI_COMMON_STATUSn(regs->offset,
						  regs->common_status_offset, 13)) << 8;
	hw_version |= readl_relaxed(csiphy->base +
		CSIPHY_3PH_CMN_CSI_COMMON_STATUSn(regs->offset,
						  regs->common_status_offset, 14)) << 16;
	hw_version |= readl_relaxed(csiphy->base +
		CSIPHY_3PH_CMN_CSI_COMMON_STATUSn(regs->offset,
						  regs->common_status_offset, 15)) << 24;

	dev_dbg(dev, "CSIPHY 3PH HW Version = 0x%08x\n", hw_version);
}

/*
 * csiphy_reset - Perform software reset on CSIPHY module
 * @csiphy: CSIPHY device
 */
static void csiphy_reset(struct csiphy_device *csiphy)
{
	struct csiphy_device_regs *regs = csiphy->regs;

	writel_relaxed(0x1, csiphy->base +
		      CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 0));
	usleep_range(5000, 8000);
}

static irqreturn_t csiphy_isr(int irq, void *dev)
{
	struct csiphy_device *csiphy = dev;
	struct csiphy_device_regs *regs = csiphy->regs;
	int i;

	for (i = 0; i < 11; i++) {
		int c = i + 22;
		u8 val = readl_relaxed(csiphy->base +
			CSIPHY_3PH_CMN_CSI_COMMON_STATUSn(regs->offset,
							  regs->common_status_offset, i));

		writel_relaxed(val, csiphy->base +
			       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, c));
	}

	writel_relaxed(0x1, csiphy->base +
		       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 10));
	writel_relaxed(0x0, csiphy->base +
		       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 10));

	for (i = 22; i < 33; i++) {
		writel_relaxed(0x0, csiphy->base +
			       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, i));
	}

	return IRQ_HANDLED;
}

/*
 * csiphy_settle_cnt_calc - Calculate settle count value
 *
 * Helper function to calculate settle count value. This is
 * based on the CSI2 T_hs_settle parameter which in turn
 * is calculated based on the CSI2 transmitter link frequency.
 *
 * Return settle count value or 0 if the CSI2 link frequency
 * is not available
 */
static u8 csiphy_settle_cnt_calc(s64 link_freq, u32 timer_clk_rate)
{
	u32 ui; /* ps */
	u32 timer_period; /* ps */
	u32 t_hs_prepare_max; /* ps */
	u32 t_hs_settle; /* ps */
	u8 settle_cnt;

	if (link_freq <= 0)
		return 0;

	ui = div_u64(1000000000000LL, link_freq);
	ui /= 2;
	t_hs_prepare_max = 85000 + 6 * ui;
	t_hs_settle = t_hs_prepare_max;

	timer_period = div_u64(1000000000000LL, timer_clk_rate);
	settle_cnt = t_hs_settle / timer_period - 6;

	return settle_cnt;
}

static void csiphy_gen1_config_lanes(struct csiphy_device *csiphy,
				     struct csiphy_config *cfg,
				     u8 settle_cnt)
{
	struct csiphy_lanes_cfg *c = &cfg->csi2->lane_cfg;
	int i, l = 0;
	u8 val;

	for (i = 0; i <= c->num_data; i++) {
		if (i == c->num_data)
			l = 7;
		else
			l = c->data[i].pos * 2;

		val = CSIPHY_3PH_LNn_CFG1_SWI_REC_DLY_PRG;
		val |= 0x17;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG1(l));

		val = CSIPHY_3PH_LNn_CFG2_LP_REC_EN_INT;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG2(l));

		val = settle_cnt;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG3(l));

		val = CSIPHY_3PH_LNn_CFG5_T_HS_DTERM |
			CSIPHY_3PH_LNn_CFG5_HS_REC_EQ_FQ_INT;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG5(l));

		val = CSIPHY_3PH_LNn_CFG6_SWI_FORCE_INIT_EXIT;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG6(l));

		val = CSIPHY_3PH_LNn_CFG7_SWI_T_INIT;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG7(l));

		val = CSIPHY_3PH_LNn_CFG8_SWI_SKIP_WAKEUP |
			CSIPHY_3PH_LNn_CFG8_SKEW_FILTER_ENABLE;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG8(l));

		val = CSIPHY_3PH_LNn_CFG9_SWI_T_WAKEUP;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG9(l));

		val = CSIPHY_3PH_LNn_TEST_IMP_HS_TERM_IMP;
		writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_TEST_IMP(l));

		val = CSIPHY_3PH_LNn_CSI_LANE_CTRL15_SWI_SOT_SYMBOL;
		writel_relaxed(val, csiphy->base +
				    CSIPHY_3PH_LNn_CSI_LANE_CTRL15(l));
	}

	val = CSIPHY_3PH_LNn_CFG1_SWI_REC_DLY_PRG;
	writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG1(l));

	if (csiphy->camss->res->version == CAMSS_660)
		val = CSIPHY_3PH_LNn_CFG4_T_HS_CLK_MISS_660;
	else
		val = CSIPHY_3PH_LNn_CFG4_T_HS_CLK_MISS;
	writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_CFG4(l));

	val = CSIPHY_3PH_LNn_MISC1_IS_CLKLANE;
	writel_relaxed(val, csiphy->base + CSIPHY_3PH_LNn_MISC1(l));
}

/*
 * csiphy_cphy_data_rate_config - Apply data-rate specific C-PHY overrides
 *
 * Applied on top of the base lane_regs. Selects the first table entry whose
 * bandwidth >= the data rate derived from @link_freq (highest entry if none
 * qualifies, default entry if @link_freq is unknown) and writes its overrides.
 */
static void csiphy_cphy_data_rate_config(struct csiphy_device *csiphy,
					 struct data_rate_reg_info *settings,
					 size_t num_settings,
					 s64 link_freq, u8 settle_cnt)
{
	struct device *dev = csiphy->camss->dev;
	const struct csiphy_lane_regs *r;
	size_t idx, i;
	u32 val;

	if (!settings || !num_settings)
		return;

	if (!link_freq) {
		/* Link frequency unknown; use the default (lowest) entry. */
		idx = CSIPHY_CPHY_DATA_RATE_DEFAULT_IDX;
	} else {
		/* First entry that satisfies the rate, else the highest. */
		for (idx = 0; idx < num_settings; idx++) {
			if (settings[idx].bandwidth >= link_freq)
				break;
		}
	}

	dev_dbg(dev,
		"CSIPHY using specific bandwidth %llu bits/s (entry %zu) for link_freq %lld\n",
		settings[idx].bandwidth, idx, link_freq);

	r = settings[idx].data_rate_reg_array;
	for (i = 0; i < settings[idx].data_rate_reg_array_size; i++, r++) {
		switch (r->csiphy_param_type) {
		case CSIPHY_SETTLE_CNT_LOWER_BYTE:
			val = settle_cnt & 0xff;
			break;
		case CSIPHY_SETTLE_CNT_HIGHER_BYTE:
			val = (settle_cnt >> 8) & 0xff;
			break;
		default:
			val = r->reg_data;
			break;
		}
		writel_relaxed(val, csiphy->base + r->reg_addr);
		if (r->delay_us)
			udelay(r->delay_us);
	}
}

static void csiphy_gen2_config_lanes(struct csiphy_device *csiphy,
				     u8 settle_cnt)
{
	const struct csiphy_lane_regs *r = csiphy->regs->lane_regs;
	int i, array_size = csiphy->regs->lane_array_size;
	u32 val;

	for (i = 0; i < array_size; i++, r++) {
		switch (r->csiphy_param_type) {
		case CSIPHY_SETTLE_CNT_LOWER_BYTE:
			val = settle_cnt & 0xff;
			break;
		case CSIPHY_SKEW_CAL:
			/* TODO: support application of skew from dt flag */
			continue;
		case CSIPHY_DNP_PARAMS:
			continue;
		default:
			val = r->reg_data;
			break;
		}
		writel_relaxed(val, csiphy->base + r->reg_addr);
		if (r->delay_us)
			udelay(r->delay_us);
	}
}

static u8 csiphy_get_lane_mask(struct csiphy_lanes_cfg *lane_cfg)
{
	u8 lane_mask = 0;
	u8 offset = 0;

	switch (lane_cfg->phy_cfg) {
	case V4L2_MBUS_CSI2_CPHY:
		offset = 1;
		break;
	case V4L2_MBUS_CSI2_DPHY:
		lane_mask = CSIPHY_3PH_CMN_CSI_COMMON_CTRL5_CLK_ENABLE;
		break;
	default:
		break;
	}

	for (int i = 0; i < lane_cfg->num_data; i++)
		lane_mask |= BIT((lane_cfg->data[i].pos * 2) + offset);

	return lane_mask;
}

static bool csiphy_is_gen2(u32 version)
{
	bool ret = false;

	switch (version) {
	case CAMSS_2290:
	case CAMSS_2390:
	case CAMSS_6150:
	case CAMSS_6350:
	case CAMSS_7280:
	case CAMSS_8250:
	case CAMSS_8280XP:
	case CAMSS_8300:
	case CAMSS_845:
	case CAMSS_8550:
	case CAMSS_8650:
	case CAMSS_8750:
	case CAMSS_8775P:
	case CAMSS_GLYMUR:
	case CAMSS_KAANAPALI:
	case CAMSS_X1E80100:
	case CAMSS_X1P42100:
		ret = true;
		break;
	}

	return ret;
}

static void csiphy_lanes_enable(struct csiphy_device *csiphy,
				struct csiphy_config *cfg,
				s64 link_freq, u8 lane_mask)
{
	struct csiphy_lanes_cfg *c = &cfg->csi2->lane_cfg;
	struct csiphy_device_regs *regs = csiphy->regs;
	struct data_rate_reg_info *data_rate_settings = NULL;
	size_t num_data_rate_settings = 0;
	u8 settle_cnt;
	u8 val;
	int i;

	switch (csiphy->camss->res->version) {
	case CAMSS_845:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sdm845[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sdm845);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = &lane_regs_sdm845_3ph[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sdm845_3ph);
		}
		break;
	case CAMSS_2290:
	case CAMSS_2390:
	case CAMSS_6150:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_qcm2290[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_qcm2290);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_6350:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sm6350[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sm6350);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_7280:
	case CAMSS_8250:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sm8250[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sm8250);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_8280XP:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sc8280xp[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sc8280xp);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_GLYMUR:
	case CAMSS_X1E80100:
	case CAMSS_X1P42100:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_x1e80100[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_x1e80100);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_8550:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sm8550[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sm8550);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_8650:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_sm8650[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sm8650);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_8750:
	case CAMSS_KAANAPALI:
		if (c->phy_cfg == V4L2_MBUS_CSI2_DPHY) {
			regs->lane_regs = &lane_regs_2_4_0[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_2_4_0);
		} else if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = NULL;
			regs->lane_array_size = 0;
		}
		break;
	case CAMSS_8300:
	case CAMSS_8775P:
		if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			regs->lane_regs = &lane_regs_sa8775p_3ph[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sa8775p_3ph);
			data_rate_settings = data_rate_settings_sa8775p_3ph;
			num_data_rate_settings = ARRAY_SIZE(data_rate_settings_sa8775p_3ph);
		} else {
			regs->lane_regs = &lane_regs_sa8775p[0];
			regs->lane_array_size = ARRAY_SIZE(lane_regs_sa8775p);
		}
		break;
	default:
		break;
	}

	if (!regs->lane_regs)
		WARN_ONCE(1, "Missing lane_regs definition!\n");

	settle_cnt = csiphy_settle_cnt_calc(link_freq, csiphy->timer_clk_rate);

	val = csiphy_get_lane_mask(c);
	writel_relaxed(val, csiphy->base +
		       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 5));

	val = CSIPHY_3PH_CMN_CSI_COMMON_CTRL6_COMMON_PWRDN_B;
	writel_relaxed(val, csiphy->base +
		       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 6));

	switch (csiphy->camss->res->version) {
	case CAMSS_8300:
	case CAMSS_8775P:
		if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY) {
			val = 0x5A;
			writel_relaxed(val, csiphy->base +
				       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 7));
			val = 0xE;
			writel_relaxed(val, csiphy->base +
				       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 0));
		} else {
			val = 0x02;
			writel_relaxed(val, csiphy->base +
				       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 7));
			writel_relaxed(val, csiphy->base +
				       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 0));
		}
		break;
	case CAMSS_7280:
	case CAMSS_8250:
	case CAMSS_8280XP:
	case CAMSS_845:
	default:
		val = 0x02;
		writel_relaxed(val, csiphy->base +
			       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 7));
		val = 0x0;
		writel_relaxed(val, csiphy->base +
			       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 0));
		break;
	}

	val = 0x00;
	writel_relaxed(val, csiphy->base +
		       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 0));

	if (csiphy_is_gen2(csiphy->camss->res->version))
		csiphy_gen2_config_lanes(csiphy, settle_cnt);
	else
		csiphy_gen1_config_lanes(csiphy, cfg, settle_cnt);

	/*
	 * For C-PHY platforms with a data-rate settings table, apply the
	 * data-rate specific overrides on top of the base lane_regs config.
	 */
	if (c->phy_cfg == V4L2_MBUS_CSI2_CPHY && data_rate_settings)
		csiphy_cphy_data_rate_config(csiphy, data_rate_settings,
					     num_data_rate_settings,
					     link_freq, settle_cnt);

	/* IRQ_MASK registers - disable all interrupts */
	for (i = 11; i < 22; i++) {
		writel_relaxed(0, csiphy->base +
			       CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, i));
	}
}

static void csiphy_lanes_disable(struct csiphy_device *csiphy,
				 struct csiphy_config *cfg)
{
	struct csiphy_device_regs *regs = csiphy->regs;

	writel_relaxed(0, csiphy->base +
			  CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 5));

	writel_relaxed(0, csiphy->base +
			  CSIPHY_3PH_CMN_CSI_COMMON_CTRLn(regs->offset, 6));
}

static int csiphy_init(struct csiphy_device *csiphy)
{
	struct device *dev = csiphy->camss->dev;
	struct csiphy_device_regs *regs;

	regs = devm_kmalloc(dev, sizeof(*regs), GFP_KERNEL);
	if (!regs)
		return -ENOMEM;

	csiphy->regs = regs;
	regs->common_status_offset = 0xb0;

	switch (csiphy->camss->res->version) {
	case CAMSS_GLYMUR:
	case CAMSS_X1E80100:
	case CAMSS_X1P42100:
	case CAMSS_8550:
	case CAMSS_8650:
		regs->offset = 0x1000;
		break;
	case CAMSS_8750:
	case CAMSS_KAANAPALI:
		/* CSPHY v2.4.0 is backward compatible with v2.3.0 settings */
		regs->offset = 0x1000;
		regs->common_status_offset = 0x138;
		break;
	default:
		regs->offset = 0x800;
		break;
	}

	return 0;
}

